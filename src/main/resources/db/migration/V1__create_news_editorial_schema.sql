CREATE TABLE editorial_sections (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL UNIQUE,
    publication_available BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT chk_editorial_sections_name CHECK (length(trim(name)) > 0)
);

CREATE TABLE app_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(80) NOT NULL UNIQUE,
    display_name VARCHAR(160) NOT NULL,
    email VARCHAR(255) UNIQUE,
    CONSTRAINT chk_app_users_username CHECK (length(trim(username)) > 0),
    CONSTRAINT chk_app_users_display_name CHECK (length(trim(display_name)) > 0),
    CONSTRAINT chk_app_users_email CHECK (email IS NULL OR position('@' IN email) > 1)
);

CREATE TABLE articles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    section_id BIGINT NOT NULL,
    author_id BIGINT NOT NULL,
    title VARCHAR(250) NOT NULL,
    article_text VARCHAR(20000) NOT NULL,
    status VARCHAR(24) NOT NULL DEFAULT 'DRAFT',
    CONSTRAINT fk_articles_section FOREIGN KEY (section_id)
        REFERENCES editorial_sections (id) ON DELETE CASCADE,
    CONSTRAINT fk_articles_author FOREIGN KEY (author_id)
        REFERENCES app_users (id) ON DELETE CASCADE,
    CONSTRAINT chk_articles_title CHECK (length(trim(title)) > 0),
    CONSTRAINT chk_articles_text CHECK (length(trim(article_text)) > 0),
    CONSTRAINT chk_articles_status CHECK (status IN ('DRAFT', 'IN_REVIEW', 'APPROVED', 'REJECTED', 'PUBLISHED'))
);

CREATE TABLE editorial_reviews (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    article_id BIGINT NOT NULL,
    decision VARCHAR(24) NOT NULL,
    remarks VARCHAR(4000),
    reviewed_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_reviews_article FOREIGN KEY (article_id)
        REFERENCES articles (id) ON DELETE CASCADE,
    CONSTRAINT chk_reviews_decision CHECK (decision IN ('APPROVED', 'REJECTED', 'NEEDS_REVISION'))
);

CREATE TABLE edition_issues (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    issue_date DATE NOT NULL,
    status VARCHAR(24) NOT NULL DEFAULT 'DRAFT',
    CONSTRAINT chk_edition_issues_status CHECK (status IN ('DRAFT', 'PUBLISHED', 'ARCHIVED'))
);

CREATE TABLE edition_issue_articles (
    issue_id BIGINT NOT NULL,
    article_id BIGINT NOT NULL,
    article_position INTEGER NOT NULL,
    CONSTRAINT pk_edition_issue_articles PRIMARY KEY (issue_id, article_id),
    CONSTRAINT uq_edition_issue_article_position UNIQUE (issue_id, article_position),
    CONSTRAINT fk_issue_articles_issue FOREIGN KEY (issue_id)
        REFERENCES edition_issues (id) ON DELETE CASCADE,
    CONSTRAINT fk_issue_articles_article FOREIGN KEY (article_id)
        REFERENCES articles (id) ON DELETE CASCADE,
    CONSTRAINT chk_edition_issue_article_position CHECK (article_position >= 0)
);

CREATE UNIQUE INDEX uq_editorial_sections_name_ci ON editorial_sections (lower(name));
CREATE UNIQUE INDEX uq_app_users_username_ci ON app_users (lower(username));
CREATE UNIQUE INDEX uq_app_users_email_ci ON app_users (lower(email)) WHERE email IS NOT NULL;

CREATE INDEX idx_articles_section_id ON articles (section_id);
CREATE INDEX idx_articles_author_id ON articles (author_id);
CREATE INDEX idx_articles_status ON articles (status);
CREATE INDEX idx_reviews_article_id ON editorial_reviews (article_id);
CREATE INDEX idx_issues_status_date ON edition_issues (status, issue_date);
CREATE INDEX idx_issue_articles_article_id ON edition_issue_articles (article_id);
